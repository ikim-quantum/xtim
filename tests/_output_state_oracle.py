"""Oracles for xtim.output_state (PLAN.md Task 3).

1. Known by construction (stim only, independent of xtim): `known_circuit` (test_output_state_oracle.py) builds an
   output exp(-i pi/8 s_k P_k) C|0> with commuting X-type axes P_k with independent columns and a random Clifford C
   computed by stim. stim's Tableau gives the expected axes, Pauli stabilizer group and stabilizer group of |S>.
2. The design's measurement oracle (xtim's exact Born check + exact engine): measure pauli_stabilizers, undo the
   rotations and measure clifford_paulis; each read is deterministic with the stated sign. It shares
   build_bare_state_framed with the helper (review I5), so it complements oracle 1.
   Task 2 review I1: a localized axis is the circuit's axis times rest stabilizers, so "circuit + undo" can be refused
   by xtim's ordinary build (non-commuting magic) although the answer is exact. Only on that
   refusal, the clifford_paulis signs are checked by the Heisenberg expansion instead: s R P R^dag =
   s prod_{A_k anticommuting with P} (1 - i s_k A_k)/sqrt2 . P, each term an exact PAULI_EXPECTATION of the circuit
   itself (no undo appended). ROUTES counts which route each call took.
No statevector, no Clifft, no 4^n, 2^d or 2^k sweep: groups are compared by GF(2) span membership with signs
(SignedGroup); the Heisenberg expansion is 2^m in m = the rotations anticommuting with P (inherent, documented)."""
import numpy as np
import stim

import xtim
from xtim import _xtim

import _exact_engine as E


def parse(p):
    return [(int(t[1:]), t[0]) for t in p.split("*")]


def ps_of(p, n, sign=1):
    s = stim.PauliString(n)
    for q, L in parse(p):
        s[q] = "_XYZ".index(L)
    return s * sign


class SignedGroup:
    """The signed Pauli group generated by commuting, independent Hermitian generators ((pauli, sign) pairs or signed
    stim PauliStrings), kept as a GF(2) row echelon basis of stim PauliStrings: polynomial, no element enumeration.
    Construction asserts the generators are Hermitian, commute pairwise and are independent (a duplicated or dependent
    generator fails), hence -I is not in the group."""

    def __init__(self, pairs, n):
        self.n, self.rows = n, []                               # [(pivot column, PauliString)], pivots distinct
        gens = [q if isinstance(q, stim.PauliString) else ps_of(q[0], n, q[1]) for q in pairs]
        for i, g in enumerate(gens):
            assert complex(g.sign).imag == 0, f"a non-Hermitian generator: {g}"
            assert all(g.commutes(h) for h in gens[:i]), f"generators do not commute: {g}"
            r = self.reduce(g)
            piv = self._first(r)
            assert piv is not None, f"a dependent (or duplicated) generator: {g}"
            self.rows.append((piv, r))
        self.rank = len(self.rows)

    @staticmethod
    def _bits(p):
        xs, zs = p.to_numpy()
        return np.concatenate([xs, zs])

    def _first(self, p):
        nz = np.flatnonzero(self._bits(p))
        return int(nz[0]) if len(nz) else None

    def reduce(self, p):
        """p times basis rows until no basis pivot is set (each row is zero on the earlier rows' pivots)."""
        p = p.copy()
        for piv, r in self.rows:
            if self._bits(p)[piv]:
                p *= r
        return p

    def member_sign(self, p):
        """+1 if p (a PauliString with real sign) is in the group, -1 if -p is, None if neither."""
        if complex(p.sign).imag:
            return None
        r = self.reduce(p)
        if self._first(r) is not None:
            return None
        return int(r.sign.real)

    def __eq__(self, other):
        """The same signed group: equal rank and every basis row of each is in the other with its sign."""
        return (self.n == other.n and self.rank == other.rank and all(other.member_sign(r) == 1 for _, r in self.rows)
                and all(self.member_sign(r) == 1 for _, r in other.rows))


def strip_ports(text):
    return "".join(l + "\n" for l in text.splitlines() if not l.strip().startswith("OUTPUT_QUBITS"))


def base_text(circuit):
    c = circuit if isinstance(circuit, xtim.Circuit) else xtim.Circuit(circuit)
    return strip_ports(c.without_noise().text)


def rot_text(rotations, undo):
    """exp(-/+ i s pi/8 P) per (P, s): forward in list order, or the inverses in reverse order (undo)."""
    out = []
    for p, s in (reversed(rotations) if undo else rotations):
        f = parse(p)
        piv = f[0][0]
        pre = [("H" if L == "X" else "H_YZ") + f" {q}" for q, L in f if L != "Z"]
        cx = [f"CX {q} {piv}" for q, _ in f[1:]]
        forward = s > 0                       # T = exp(-i pi/8 Z) up to phase
        gate = ("T_DAG" if forward else "T") if undo else ("T" if forward else "T_DAG")
        out += pre + cx + [f"{gate} {piv}"] + cx[::-1] + pre[::-1]
    return "".join(l + "\n" for l in out)


ROUTES = {"undo": 0, "heisenberg": 0}


def assert_measures(text, paulis, shots=4):
    """Each (pauli, sign) read with MPP after text is deterministic with that sign. Returns False (asserting nothing)
    iff xtim refuses text itself (a rejected build, not a parse error or a wrong sign)."""
    if not paulis:
        return True
    t = text + "".join(f"MPP {p}\nDETECTOR rec[-1]\n" for p, _ in paulis)
    det = _xtim.detector_determinism(t)
    if not det["ok"]:
        assert not det["errors"], det["errors"]            # the oracle's own text must parse
        assert det["rejected"], det                         # review m4: fall back only on a true build rejection
        return False
    nd, k = det["num_detectors"], len(paulis)
    assert set(range(nd - k, nd)) <= set(det["deterministic_detectors"]), "a read is not deterministic"
    try:
        sampler = E.exact_sampler(xtim.Circuit(t), seed=5)
    except (xtim.XtimTwirlRefusal, xtim.XtimRejectError):
        return False
    m = np.asarray(sampler.sample(shots))
    assert (m[:, -k:] == np.array([s < 0 for _, s in paulis])).all()
    return True


def _unsigned(p):
    """(unsigned MPP string or "" for identity, phase) of a stim.PauliString."""
    return "*".join(f"{'_XYZ'[p[q]]}{q}" for q in range(len(p)) if p[q]), complex(p.sign)


def assert_heisenberg(text, rotations, paulis, n, shots=4):
    """<psi| s R P R^dag |psi> = 1 for each (P, s), from exact Pauli expectations of the circuit (see the module doc)."""
    cols, plan = [], []
    for p, s in paulis:
        P = ps_of(p, n)
        anti = [(ps_of(a, n), sa) for a, sa in rotations if not ps_of(a, n).commutes(P)]
        terms = []
        for mask in range(1 << len(anti)):
            op, coeff = stim.PauliString(n), complex(s) * 2 ** (-len(anti) / 2)
            for i, (A, sa) in enumerate(anti):
                if (mask >> i) & 1:
                    op *= A
                    coeff *= -1j * sa
            op *= P
            u, ph = _unsigned(op)
            terms.append((coeff * ph, u))
        plan.append(terms)
        cols += [u for _, u in terms if u]
    index = {u: i for i, u in enumerate(dict.fromkeys(cols))}
    t = text + "".join(f"PAULI_EXPECTATION({i}) {u}\n" for u, i in index.items())
    _, ev = E.exact_detector_sampler(xtim.Circuit(t), seed=7).sample(shots, return_expectations=True)
    ev = np.asarray(ev)
    for (p, s), terms in zip(paulis, plan):
        val = sum(c * (ev[:, index[u]] if u else 1.0) for c, u in terms)
        assert np.allclose(val, 1.0, atol=1e-9), (p, s, val)


def assert_state(circuit, st):
    """The design's verification: MPP reads of pauli_stabilizers on the circuit, and of clifford_paulis after the undo.
    If (only if) xtim refuses the undo circuit, the clifford_paulis are checked by assert_heisenberg (review I1);
    ROUTES counts the two. A wrong sign or a non-deterministic read fails either way."""
    base = base_text(circuit)
    assert assert_measures(base, list(st.pauli_stabilizers)), "xtim refused the circuit itself"
    assert len(st.pauli_stabilizers) + len(st.clifford_paulis) == len(st.qubits)
    if not st.clifford_paulis:
        return "undo"
    if assert_measures(base + rot_text(list(st.rotations), undo=True), list(st.clifford_paulis)):
        ROUTES["undo"] += 1
        return "undo"
    n = 1 + max(q for p, _ in list(st.rotations) + list(st.clifford_paulis) for q, _ in parse(p))
    assert_heisenberg(base, list(st.rotations), list(st.clifford_paulis), n)
    ROUTES["heisenberg"] += 1
    return "heisenberg"
