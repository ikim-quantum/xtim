"""The factored law vs a GOLDEN record of the retired branch walk on circuits too large for
the dense oracle: tests/data/forced_walk_golden.json, generated by the walk at xtim 57e728a
(method="enumerate"; generator source and commit inside the JSON) — cultivation_d5 (50 single
faults spread over the sites, the 7 folded record flips, 10 weight-2/3 sets) and ftqcp's qrm15
magic-t-prep Choi program (20 queries), each aggregated by (detectors, observables, decisions)
with probability-weighted conditional expectations. Same compiled program => same reference:
compared exactly, probabilities and conditional expectations to 1e-12."""
import json
import os

import numpy as np
import pytest

import xtim

from _orig_examples import ORIG_EXAMPLES, load_orig  # noqa: E402,F401
GOLDEN = os.path.join(os.path.dirname(__file__), "data", "forced_walk_golden.json")


def _faults(fs):
    return [{"record": f["record"]} if isinstance(f, dict) else (f[0], f[1], f[2]) for f in fs]


def _law_agg(law):
    out = {}
    for i in range(len(law.probabilities)):
        k = "".join(map(str, law.detectors[i].astype(int))) + "|" + \
            "".join(map(str, law.observables[i].astype(int))) + "|" + \
            "".join(map(str, law.decisions[i].astype(int)))
        assert k not in out
        out[k] = (float(law.probabilities[i]), np.asarray(law.expectations[i], float))
    return out


with open(GOLDEN) as fh:
    DATA = json.load(fh)


def test_golden_provenance():
    assert DATA["commit"] == "57e728a" and "method=\"enumerate\"" in DATA["generator_source"]
    assert len(DATA["circuits"]["cultivation_d5"]["queries"]) == 67
    assert len(DATA["circuits"]["qrm15_magic_t_prep_choi"]["queries"]) == 20


@pytest.mark.parametrize("name", sorted(DATA["circuits"]))
def test_law_equals_walk_golden(name):
    c = DATA["circuits"][name]
    text = load_orig(c["example"]).text if "example" in c else c["text"]
    sim = xtim.Circuit(text).compile_exact_branches()
    worst = 0.0
    for q in c["queries"]:
        law = _law_agg(sim.exact_branches(_faults(q["faults"])))
        gold = {k: (p, np.asarray(e, float)) for k, (p, e) in q["law"].items()}
        for k in set(law) | set(gold):
            pl, el = law.get(k, (0.0, None))
            pg, eg = gold.get(k, (0.0, None))
            worst = max(worst, abs(pl - pg))
            assert abs(pl - pg) < 1e-12, (q["faults"], k, pl, pg)
            if pl > 1e-9 and pg > 1e-9 and len(eg):
                d = float(np.abs(el - eg).max())
                worst = max(worst, d)
                assert d < 1e-12, (q["faults"], k, el, eg)
    print(name, "worst", worst)
