// reduce: the row-by-row walk over the dense rref (ascending set pivot columns), the verdict by the generators.
void walk_dense(const DenseGroupPlanes& B, Pauli& w) {
    const int n = B.n_qubits, NWq = (n + 63) / 64;
    for (int blk = 0; blk < 2; ++blk) {
        std::vector<uint64_t>& vec = blk ? w.z : w.x;
        for (int wq = 0; wq < NWq; ++wq) {
            uint64_t word = vec[(size_t)wq];
            while (word) {
                const int b = __builtin_ctzll(word);
                const int c = (blk ? n : 0) + wq * 64 + b;
                const int r = B.col_to_row[(size_t)c];
                if (r >= 0) {
                    pmul_into(w, B.rref[(size_t)r]);
                    word = (b == 63) ? 0 : (vec[(size_t)wq] & (~0ULL << (b + 1)));
                } else {
                    word &= word - 1;
                }
            }
        }
    }
}
Membership reduce_dense(const DenseGroupPlanes& B, const Pauli& p) {
    Pauli w = p;
    walk_dense(B, w);
    bool zero = true;
    for (size_t i = 0; i < w.x.size(); ++i) if (w.x[i] || w.z[i]) { zero = false; break; }
    if (zero) return Membership::in_group(((w.phase >> 1) & 1) ? -1 : +1, w);
    for (const Pauli& g : B.gens) if (Pauli::anticommute_bit(w, g)) return Membership::anti(w);
    return Membership::logical(w);
}

void phi_dense(const DenseGroupPlanes& B, const Pauli& Q, std::vector<uint64_t>& out) {
    out.assign((size_t)B.words, 0);
    for (int q = 0; q < B.n_qubits; ++q) {
        if (Q.xbit(q)) { const uint64_t* c = B.col(q, false); for (int t = 0; t < B.words; ++t) out[(size_t)t] ^= c[t]; }
        if (Q.zbit(q)) { const uint64_t* c = B.col(q, true); for (int t = 0; t < B.words; ++t) out[(size_t)t] ^= c[t]; }
    }
}

// tier1_signs, pre-S2 (twirl_signs.cpp's word forms).
Tier1Result tier1_dense(const DenseGroupPlanes& G, const DiagNormalForm& nf) {
    const int W = G.words, n = G.n_qubits;
    Tier1Result r;
    r.sign.assign(W, 0);
    r.active.assign(W, 0);
    if (W == 0) return r;
    for (int q = 0; q < n; ++q) {
        if (nf.prefix.xbit(q)) { const uint64_t* c = G.col(q, false); for (int w = 0; w < W; ++w) r.sign[w] ^= c[w]; }
        if (nf.prefix.zbit(q)) { const uint64_t* c = G.col(q, true); for (int w = 0; w < W; ++w) r.sign[w] ^= c[w]; }
    }
    std::vector<uint64_t> ones(W, 0), twos(W, 0);
    for (int q = 0; q < n; ++q) {
        if (!nf.a[q]) continue;
        const uint64_t* c = G.col(q, true);
        for (int w = 0; w < W; ++w) { const uint64_t carry = ones[w] & c[w]; ones[w] ^= c[w]; twos[w] ^= carry; }
    }
    for (int w = 0; w < W; ++w) r.sign[w] ^= twos[w];
    for (const auto& e : nf.cz) {
        const uint64_t* cq = G.col(e.first, true);
        const uint64_t* cqp = G.col(e.second, true);
        for (int w = 0; w < W; ++w) r.sign[w] ^= (cq[w] & cqp[w]);
    }
    std::vector<uint64_t> pat(W);
    for (int j = 0; j < n; ++j) {
        std::fill(pat.begin(), pat.end(), 0);
        bool any = false;
        if (nf.a[j]) { any = true; const uint64_t* c = G.col(j, true); for (int w = 0; w < W; ++w) pat[w] ^= c[w]; }
        for (const auto& e : nf.cz) {
            int o = -1;
            if (e.first == j) o = e.second;
            else if (e.second == j) o = e.first;
            if (o < 0) continue;
            any = true;
            const uint64_t* c = G.col(o, true);
            for (int w = 0; w < W; ++w) pat[w] ^= c[w];
        }
        if (any) for (int w = 0; w < W; ++w) r.active[w] |= pat[w];
    }
    return r;
}

std::vector<int8_t> z_axis_dense(const DenseGroupPlanes& B) {
    std::vector<int8_t> s((size_t)B.n_qubits, 0);
    for (int r = 0; r < B.rank; ++r) {
        if (B.pivcol[(size_t)r] < B.n_qubits) continue;
        const Pauli& row = B.rref[(size_t)r];
        const int piv = B.pivcol[(size_t)r] - B.n_qubits;
        int pop = 0, only = -1;
        for (size_t w = 0; w < row.z.size(); ++w)
            for (uint64_t word = row.z[w]; word; word &= word - 1) { only = (int)(w * 64 + __builtin_ctzll(word)); ++pop; }
        if (pop == 1 && only == piv) s[(size_t)piv] = ((row.phase >> 1) & 1) ? (int8_t)-1 : (int8_t)+1;
    }
    return s;
}

uint64_t token_dense(const DenseGroupPlanes& B) {
    uint64_t h = 1469598103934665603ull;
    auto mix = [&](uint64_t v) { for (int b = 0; b < 8; ++b) { h ^= (uint8_t)(v >> (8 * b)); h *= 1099511628211ull; } };
    mix((uint64_t)B.n_qubits);
    mix((uint64_t)B.n_gens);
    for (const Pauli& g : B.gens) {
        for (uint64_t w : g.x) mix(w);
        for (uint64_t w : g.z) mix(w);
        mix((uint64_t)g.phase);
    }
    return h;
}

// QW-E C1: the S2-T5 identity_token verbatim (each generator's dense words materialised, every byte mixed), the oracle
// of the sparse form (zero-word runs as powers of the FNV prime).
uint64_t token_densified(const CertifiedGroupPlanes& A) {
    uint64_t h = 1469598103934665603ull;
    auto mix = [&](uint64_t v) { for (int b = 0; b < 8; ++b) { h ^= (uint8_t)(v >> (8 * b)); h *= 1099511628211ull; } };
    mix((uint64_t)A.n_qubits);
    mix((uint64_t)A.n_gens);
    std::vector<uint64_t> wx, wz;
    for (const SparsePauli& g : A.gens) {
        const size_t W = (size_t)(g.n + 63) / 64;
        wx.assign(W, 0);
        wz.assign(W, 0);
        for (int32_t q : g.x) wx[(size_t)q >> 6] |= 1ULL << (q & 63);
        for (int32_t q : g.z) wz[(size_t)q >> 6] |= 1ULL << (q & 63);
        for (uint64_t w : wx) mix(w);
        for (uint64_t w : wz) mix(w);
        mix((uint64_t)g.phase);
    }
    return h;
}
